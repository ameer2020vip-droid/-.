/**
 * Smart Action Engine
 * Analyzes the incident, past student records, track, and calculates official recommended actions
 */
export function calculateSmartAction(params: {
  track: CaseIntakeTrack;
  violationTitle?: string;
  violationCode?: string;
  studentId?: string;
  studentHistory?: any[];
  incidentDate?: string;
  degree?: ViolationDegree | string;
  studentPastViolationsCount?: number;
  studentPastTardinessCount?: number;
  studentPastAbsencesCount?: number;
}): SmartActionEngineResult {
  const {
    track,
    violationTitle = '',
    degree,
    studentPastViolationsCount = 0,
    studentPastTardinessCount = 0,
  } = params;

  // 1. Specialized Track Handlers
  if (track === 'child_protection') {
    return {
      violationCode: 'CP-SAFE-01',
      degreeName: 'الدرجة الرابعة (شديدة الخطورة - حماية طفل)',
      gradeDeduction: 20,
      repetitionCount: 1,
      previousActions: ['بروتوكول حماية الطفل الاتحادي (قانون وديمة)'],
      suggestedAction:
        'إحالة سرية وفورية لاختصاصي حماية الطفل ومركز حماية الطفل (116111). يُحظر التحقيق العشوائي أو إفشاء هوية الطفل.',
      responsibleRole: 'مدير المدرسة ومنسق حماية الطفل المعتمد حصراً',
      requiredForms: ['استمارة تبليغ حماية طفل سرية مشفرة'],
      requiresPrincipalApproval: true,
      requiresBehaviorCommittee: false,
      requiresSpecializedReferral: true,
      specializedReferralEntity: 'مركز حماية الطفل بوزارة الداخلية (116111) والوحدة الوزارية',
      caseBundleSupported: false,
    };
  }

  if (track === 'suspected_substance') {
    return {
      violationCode: '4-01',
      degreeName: 'الدرجة الرابعة (شديدة الخطورة)',
      gradeDeduction: 20,
      repetitionCount: studentPastViolationsCount + 1,
      previousActions: studentPastViolationsCount > 0 ? ['سوابق مخالفات سلوكية مسجلة'] : ['الواقعة الأولى'],
      suggestedAction:
        'التحفظ الاحترازي الفوري، إبلاغ الجهات الأمنية المختصة، عقد اجتماع طارئ للجنة السلوك وتطبيق الفصل التأديبي وفق القرار الوزاري.',
      responsibleRole: 'مدير المدرسة ولجنة إدارة السلوك والجهات الأمنية',
      requiredForms: [
        'محضر ضبط ومصادرة',
        'محضر اجتماع طارئ للجنة إدارة السلوك',
        'إحالة رسمية للجهات المختصة',
        'نموذج 6 (تقرير مخالفة)',
      ],
      requiresPrincipalApproval: true,
      requiresBehaviorCommittee: true,
      requiresSpecializedReferral: true,
      specializedReferralEntity: 'الجهات الأمنية المختصة والرعاية الاجتماعية',
      caseBundleSupported: true,
    };
  }

  if (track === 'bullying') {
    const rep = studentPastViolationsCount + 1;
    return {
      violationCode: '3-01',
      degreeName: 'الدرجة الثالثة (جسيمة - تنمر)',
      gradeDeduction: rep === 1 ? 8 : 12,
      repetitionCount: rep,
      previousActions: rep > 1 ? ['تنبيه واستدعاء سابق لولي الأمر'] : ['الواقعة الأولى المرصودة'],
      suggestedAction:
        'عقد اجتماع فوري للجنة السلوك، استدعاء ولي أمر الطالب، حسم درجات السلوك، وتطبيق خطة تعديل سلوك علاجية مع تقديم دعم نفسي للضحية.',
      responsibleRole: 'مساعد المدير والمرشد الطلابي ولجنة السلوك',
      requiredForms: [
        'نموذج 6 (تقرير مخالفة)',
        'نموذج 7 (إخطار حسم درجات)',
        'نموذج 8 (استدعاء ولي أمر)',
        'نموذج 10 (تعهد ولي الأمر)',
        'خطة تعديل سلوك علاجية',
        'محضر لجنة السلوك',
      ],
      requiresPrincipalApproval: true,
      requiresBehaviorCommittee: true,
      requiresSpecializedReferral: rep >= 2,
      specializedReferralEntity: 'فريق الرعاية الطلابية وإدارة الإرشاد الأكاديمي',
      caseBundleSupported: true,
    };
  }

  if (track === 'positive_behavior') {
    return {
      violationCode: 'POS-01',
      degreeName: 'سلوك إيجابي متميز (تعزيز وتمكين)',
      gradeDeduction: 0,
      repetitionCount: 1,
      previousActions: ['مبادرة تطوعية / تفوق سلوكي'],
      suggestedAction:
        'منح شهادة شكر وتقدير، إضافة نقاط تشجيعية، وتعويض درجات السلوك المحسومة سابقاً بعد اعتماد لجنة السلوك.',
      responsibleRole: 'المرشد الطلابي ومعلمو المواد',
      requiredForms: ['شهادة تقدير وسلوك متميز', 'سجل تعويض درجات السلوك المعتمد'],
      requiresPrincipalApproval: true,
      requiresBehaviorCommittee: false,
      requiresSpecializedReferral: false,
      caseBundleSupported: false,
    };
  }

  if (track === 'tardiness') {
    const count = studentPastTardinessCount + 1;
    if (count === 1) {
      return {
        violationCode: '1-01',
        degreeName: 'الدرجة الأولى (بسيطة)',
        gradeDeduction: 0,
        repetitionCount: 1,
        previousActions: ['المرة الأولى'],
        suggestedAction: 'تنبيه شفهي وتوثيق في سجل التأخير اليومي.',
        responsibleRole: 'مشرف الجناح ومسؤول البوابة',
        requiredForms: ['إشعار رسالة نصية لولي الأمر'],
        requiresPrincipalApproval: false,
        requiresBehaviorCommittee: false,
        requiresSpecializedReferral: false,
        caseBundleSupported: false,
      };
    } else if (count === 2) {
      return {
        violationCode: '1-01',
        degreeName: 'الدرجة الأولى (بسيطة)',
        gradeDeduction: 0,
        repetitionCount: 2,
        previousActions: ['تنبيه شفهي في المرة الأولى'],
        suggestedAction: 'توجيه تربوي من المرشد الطلابي وإشعار ولي الأمر عبر الرسائل الرسمية.',
        responsibleRole: 'المرشد الطلابي',
        requiredForms: ['إشعار رسمي لولي الأمر'],
        requiresPrincipalApproval: false,
        requiresBehaviorCommittee: false,
        requiresSpecializedReferral: false,
        caseBundleSupported: false,
      };
    } else {
      return {
        violationCode: '1-01',
        degreeName: 'الدرجة الأولى (بسيطة - متكررة)',
        gradeDeduction: 1,
        repetitionCount: count,
        previousActions: [`سجل تأخر ${count - 1} مرات سابقة`],
        suggestedAction:
          'تحرير نموذج (9) تنبيه خطي للطالب + إشعار ولي الأمر بنموذج (7) وحسم درجة واحدة من درجات السلوك.',
        responsibleRole: 'مساعد المدير والمرشد الطلابي',
        requiredForms: ['نموذج 9 (تنبيه خطي)', 'نموذج 7 (إخطار ولي الأمر)', 'نموذج 8 (استدعاء إذا بلغ 4 مرات)'],
        requiresPrincipalApproval: true,
        requiresBehaviorCommittee: false,
        requiresSpecializedReferral: false,
        caseBundleSupported: true,
      };
    }
  }

  // 2. Standard Catalog Matching
  const matched = BYLAW_VIOLATIONS_CATALOG.find(
    (v) =>
      v.title.toLowerCase().includes(violationTitle.toLowerCase()) ||
      violationTitle.toLowerCase().includes(v.title.toLowerCase())
  );

  const finalDegree: ViolationDegree = matched
    ? matched.degree
    : (degree as ViolationDegree) || 'الدرجة الثانية (متوسطة)';
  const repetition = studentPastViolationsCount + 1;

  let deduction = 1;
  let suggested = '';
  let forms = ['نموذج 6 (تقرير مخالفة)', 'نموذج 7 (إخطار ولي أمر)'];
  let requiresPrincipal = false;
  let requiresCommittee = false;
  let requiresSpecialized = false;
  let responsible = 'المرشد الطلابي';

  if (finalDegree.includes('الدرجة الأولى')) {
    deduction = repetition === 1 ? 0 : 1;
    suggested =
      repetition === 1
        ? 'تنبيه شفهي مع توجيه وإرشاد وتوثيق الواقعة.'
        : 'تنبيه خطي بنموذج (9) وحسم درجة سلوك وإخطار ولي الأمر بنموذج (7).';
    forms = repetition === 1 ? ['تنبيه شفهي موثق'] : ['نموذج 9 (تنبيه خطي)', 'نموذج 7 (إخطار ولي الأمر)'];
    responsible = 'معلم الحصة ومشرف الجناح والمرشد';
  } else if (finalDegree.includes('الدرجة الثانية')) {
    deduction = repetition === 1 ? 2 : 4;
    suggested =
      repetition === 1
        ? 'تقرير مخالفة بنموذج (6) + إخطار حسم درجتين بنموذج (7) + استدعاء ولي الأمر بنموذج (8) وتوقيع تعهد.'
        : 'حسم 4 درجات + استدعاء عاجل لولي الأمر وتوقيع تعهد تكرار المخالفات (نموذج 10) وبدء خطة تعديل سلوك.';
    forms = [
      'نموذج 6 (تقرير مخالفة)',
      'نموذج 7 (إخطار حسم درجات)',
      'نموذج 8 (استدعاء ولي أمر)',
      'نموذج 10 (تعهد ولي الأمر)',
      'خطة تعديل سلوك',
    ];
    requiresPrincipal = true;
    responsible = 'مساعد المدير والمرشد الطلابي';
  } else if (finalDegree.includes('الدرجة الثالثة')) {
    deduction = repetition === 1 ? 8 : 12;
    suggested =
      'إحالة فورية للجنة إدارة السلوك المدرسية، استدعاء عاجل لولي الأمر، حسم 8 درجات، إيقاف مؤقت مع خطة تعديل سلوك مكثفة.';
    forms = [
      'نموذج 6 (تقرير مخالفة)',
      'نموذج 7 (إخطار حسم 8 درجات)',
      'نموذج 8 (استدعاء عاجل لولي الأمر)',
      'نموذج 10 (تعهد ولي الأمر)',
      'محضر اجتماع لجنة السلوك',
      'خطة تعديل سلوك علاجية',
    ];
    requiresPrincipal = true;
    requiresCommittee = true;
    requiresSpecialized = repetition >= 2;
    responsible = 'مدير المدرسة ولجنة إدارة السلوك';
  } else {
    // Fourth Degree
    deduction = 20;
    suggested =
      'تحفظ فوري، اجتماع طارئ للجنة السلوك، إحالة للجهات المختصة وفريق حماية الطفل وحسم 20 درجة مع توصية بالفصل التأديبي.';
    forms = ['محضر ضبط ومصادرة', 'تقرير واقعة جسيمة', 'محضر لجنة السلوك الطارئ', 'إحالة رسمية'];
    requiresPrincipal = true;
    requiresCommittee = true;
    requiresSpecialized = true;
    responsible = 'مدير المدرسة ولجنة إدارة السلوك والجهات المختصة';
  }

  return {
    violationCode: matched?.code || 'GEN-01',
    degreeName: finalDegree,
    gradeDeduction: deduction,
    repetitionCount: repetition,
    previousActions:
      studentPastViolationsCount > 0
        ? [`سجل ${studentPastViolationsCount} مخالفات سابقة مسجلة في ملف الطالب`]
        : ['لا توجد مخالفات سابقة مسجلة لهذا الطالب'],
    suggestedAction: suggested,
    responsibleRole: responsible,
    requiredForms: forms,
    requiresPrincipalApproval: requiresPrincipal,
    requiresBehaviorCommittee: requiresCommittee,
    requiresSpecializedReferral: requiresSpecialized,
    specializedReferralEntity: matched?.specializedEntity,
    caseBundleSupported: finalDegree.includes('الثانية') || finalDegree.includes('الثالثة'),
  };
}
